const r = require('express').Router();
const c = require('../controllers/categoryController');
const auth = require('../middleware/auth');
const ah = require('../utils/ah');
r.use(auth);
r.get('/', ah(c.list));
r.post('/', ah(c.create));
r.put('/:id', ah(c.update));
r.delete('/:id', ah(c.remove));
module.exports = r;
